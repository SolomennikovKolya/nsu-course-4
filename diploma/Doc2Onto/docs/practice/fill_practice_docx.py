def fill_supervisor_review() -> None:
    src = PRACTICE_DIR / "Соломенников_Николай_Александрович_Отзыв_руководителя_практики.docx"
    dst = PRACTICE_DIR / "Соломенников_Николай_Александрович_Отзыв_руководителя_практики_filled.docx"
    print(f"\n[ОТЗЫВ] {src.name}")

    doc = Document(str(src))

    # --- Должность обучающегося (P18) ----------------------------------------
    p_position = find_paragraph(
        doc.paragraphs,
        lambda t: t.startswith("Должность обучающегося на практике"),
    )
    if p_position is not None:
        replace_yellow_runs(p_position, "—")
        print("  [+] Должность обучающегося: «—» (не трудоустроен)")

    # --- Тема индивидуального задания (P20) ----------------------------------
    p_topic = find_paragraph(
        doc.paragraphs,
        lambda t: t.startswith("Тема индивидуального задания"),
    )
    if p_topic is not None:
        replace_yellow_runs(p_topic, TOPIC)
        print(f"  [+] Тема: «{TOPIC}»")

    # --- Оценка достигнутых результатов (P25) --------------------------------
    achievements = (
        "В ходе практики обучающимся достигнуты следующие результаты, "
        "запланированные в программе практики и индивидуальном задании: "
        "проведён анализ существующих программных решений сходного назначения "
        "и сформулированы требования к реализации; реализованы ключевые "
        "компоненты программной системы автоматизированного извлечения знаний "
        "из документов, включая модули преобразования документов, извлечения "
        "значений полей, построения и интеграции графа фактов; реализована "
        "подсистема взаимодействия с большой языковой моделью и средства "
        "автоматизированной генерации шаблонов; разработан графический "
        "пользовательский интерфейс; проведена апробация системы на наборе "
        "реальных документов кафедры; подготовлен текст отчёта о практике и "
        "проект пояснительной записки к выпускной квалификационной работе."
    )
    p_results = find_paragraph(
        doc.paragraphs, lambda t: t.strip() == "_________________",
    )
    if p_results is not None:
        replace_paragraph_text(p_results, achievements)
        print("  [+] Оценка достигнутых результатов заполнена")

    # Удаление сноски-комментария после оценки результатов
    p_footnote = find_paragraph(
        doc.paragraphs,
        lambda t: t.startswith("*перечислить результаты"),
    )
    if p_footnote is not None:
        delete_paragraph(p_footnote)
        print("  [+] Удалена сноска-комментарий")

    # --- Удаление инструкции «СТРУКТУРА ОТЗЫВА» и пунктов под ней ------------
    paragraphs = list(doc.paragraphs)
    delete_from = None
    delete_to = None
    for i, p in enumerate(paragraphs):
        if "СТРУКТУРА ОТЗЫВА" in p.text:
            delete_from = i
        if delete_from is not None and p.text.startswith(
            "выводы о профессиональной пригодности"
        ):
            delete_to = i
            break
    if delete_from is not None and delete_to is not None:
        anchor = paragraphs[delete_from - 1] if delete_from > 0 else None
        for p in paragraphs[delete_from:delete_to + 1]:
            delete_paragraph(p)
        print(f"  [+] Удалена инструкция «СТРУКТУРА ОТЗЫВА» "
              f"(параграфы {delete_from}..{delete_to})")
        if anchor is not None:
            add_paragraphs_after(anchor, REVIEW_BODY, style_from=anchor)
            print(f"  [+] Добавлено {len(REVIEW_BODY)} параграфов отзыва")

    # --- Очистка highlight у X-ов в таблице компетенций ----------------------
    cleared = 0
    for table in doc.tables:
        for row in table.rows:
            for cell in row.cells:
                for para in cell.paragraphs:
                    for run in para.runs:
                        if is_yellow(run):
                            clear_yellow(run)
                            cleared += 1
    print(f"  [+] Снят highlight в таблице с {cleared} run-ов")

    doc.save(str(dst))
    print(f"  >> Сохранено: {dst.name}")


