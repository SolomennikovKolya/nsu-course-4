# =============================================================================
# Утилиты для работы с docx
# =============================================================================


def is_yellow(run) -> bool:
    color = run.font.highlight_color
    return color is not None and color == WD_COLOR_INDEX.YELLOW


def clear_yellow(run) -> None:
    run.font.highlight_color = None


def iter_paragraphs(doc) -> Iterable[Paragraph]:
    yield from doc.paragraphs
    for table in doc.tables:
        for row in table.rows:
            for cell in row.cells:
                for para in cell.paragraphs:
                    yield para


def delete_paragraph(paragraph: Paragraph) -> None:
    """Удаляет параграф из документа."""
    element = paragraph._element
    element.getparent().remove(element)
    paragraph._p = paragraph._element = None  # type: ignore[assignment]


def replace_paragraph_text(paragraph: Paragraph, new_text: str) -> None:
    """
    Заменяет текст параграфа: первый run получает новый текст и теряет
    жёлтый highlight, остальные жёлтые run-ы очищаются.
    Сохраняется форматирование первого run-а.
    """
    runs = paragraph.runs
    if not runs:
        paragraph.add_run(new_text)
        return
    # Сначала чистим: первый run переписываем, остальные обнуляем.
    runs[0].text = new_text
    clear_yellow(runs[0])
    for run in runs[1:]:
        if run.text:
            run.text = ""
        if is_yellow(run):
            clear_yellow(run)


def replace_yellow_runs(paragraph: Paragraph, new_text: str) -> None:
    """
    Заменяет содержимое всех жёлтых run-ов параграфа: первый жёлтый run
    получает new_text, остальные обнуляются. Не-жёлтые run-ы не трогаем.
    """
    yellow_runs = [r for r in paragraph.runs if is_yellow(r)]
    if not yellow_runs:
        return
    yellow_runs[0].text = new_text
    clear_yellow(yellow_runs[0])
    for run in yellow_runs[1:]:
        run.text = ""
        clear_yellow(run)


def find_paragraph(
    paragraphs: List[Paragraph],
    predicate: Callable[[str], bool],
) -> Optional[Paragraph]:
    for p in paragraphs:
        if predicate(p.text):
            return p
    return None


def add_paragraph_after(
    after: Paragraph,
    text: str,
    *,
    style_from: Optional[Paragraph] = None,
) -> Paragraph:
    """
    Создаёт новый параграф сразу после ``after`` с указанным текстом.
    Если задан ``style_from``, новый параграф наследует стиль и
    форматирование первого run-а ``style_from``.
    """
    src = style_from or after
    new_p_el = deepcopy(src._element)
    # Чистим текст в новом параграфе.
    for r in new_p_el.findall(qn("w:r")):
        new_p_el.remove(r)
    after._element.addnext(new_p_el)
    new_para = Paragraph(new_p_el, after._parent)
    run = new_para.add_run(text)
    # Если у источника был run, наследуем его базовое форматирование.
    if src.runs:
        src_run = src.runs[0]
        run.bold = src_run.bold
        run.italic = src_run.italic
        if src_run.font.name:
            run.font.name = src_run.font.name
        if src_run.font.size:
            run.font.size = src_run.font.size
    clear_yellow(run)
    return new_para


def add_paragraphs_after(
    after: Paragraph,
    texts: List[str],
    *,
    style_from: Optional[Paragraph] = None,
) -> Paragraph:
    """Возвращает последний созданный параграф."""
    cursor = after
    for text in texts:
        cursor = add_paragraph_after(cursor, text, style_from=style_from)
    return cursor


def set_cell_text(cell, text: str, *, keep_first_para_format: bool = True) -> None:
    """
    Полностью заменяет содержимое ячейки таблицы одним параграфом
    с указанным текстом, сохраняя форматирование первого параграфа.
    """
    paragraphs = cell.paragraphs
    if not paragraphs:
        cell.add_paragraph(text)
        return
    first = paragraphs[0]
    if keep_first_para_format and first.runs:
        first.runs[0].text = text
        clear_yellow(first.runs[0])
        for run in first.runs[1:]:
            run.text = ""
            clear_yellow(run)
    else:
        for run in first.runs:
            run.text = ""
        first.add_run(text)
    # Удаляем все остальные параграфы ячейки.
    for p in paragraphs[1:]:
        delete_paragraph(p)


