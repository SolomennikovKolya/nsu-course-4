def fill_practice_report() -> None:
    src = PRACTICE_DIR / "Соломенников_Николай_Александрович_Отчет_о_практике.docx"
    dst = PRACTICE_DIR / "Соломенников_Николай_Александрович_Отчет_о_практике_filled.docx"
    print(f"\n[ОТЧЁТ] {src.name}")

    doc = Document(str(src))

    # --- Тема задания (P20) --------------------------------------------------
    p_topic = find_paragraph(doc.paragraphs, lambda t: t.startswith("Тема задания:"))
    if p_topic is not None:
        replace_yellow_runs(p_topic, TOPIC)
        print(f"  [+] Тема: «{TOPIC}»")

    # --- Удаление инструкций «Структура отчёта», «Требования для оформления»
    # Удаляем все параграфы, начиная с «Структура отчета (удалить после…)»
    # и до конца документа (это инструкция).
    paragraphs = list(doc.paragraphs)
    delete_from = None
    for i, p in enumerate(paragraphs):
        if "Структура отчета" in p.text and "удалить" in p.text.lower():
            delete_from = i
            break
    if delete_from is None:
        # Альтернативный поиск
        for i, p in enumerate(paragraphs):
            if "Структура отчёта" in p.text or "Структура отчета" in p.text:
                delete_from = i
                break

    # Сохраняем последний параграф «до удаления», чтобы вставить туда содержание.
    insertion_anchor = None
    if delete_from is not None:
        insertion_anchor = paragraphs[delete_from - 1] if delete_from > 0 else paragraphs[0]
        for p in paragraphs[delete_from:]:
            delete_paragraph(p)
        print(f"  [+] Удалены инструкции с параграфа №{delete_from}")

    # --- Добавление текста отчёта --------------------------------------------
    if insertion_anchor is not None:
        add_paragraphs_after(
            insertion_anchor,
            REPORT_BODY,
            style_from=insertion_anchor,
        )
        print(f"  [+] Добавлено {len(REPORT_BODY)} параграфов основного текста")

    doc.save(str(dst))
    print(f"  >> Сохранено: {dst.name}")


